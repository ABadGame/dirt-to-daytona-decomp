#!/usr/bin/env python3
"""Run SN Systems ngcld (the ProDG GameCube linker) from ninja.

ngcld needs SN_NGC_PATH pointing at its folder and can't read response files, so this
wrapper reads ninja's response file and writes a temporary linker script that starts
with INPUT(...) for every object, followed by the project's script.

Usage:
  ngcld.py --prodg DIR --script SCRIPT --rsp FILE -o OUT [--map MAP] [--wrapper CMD]

--wrapper runs ngcld through wine/wibo on non-Windows hosts.
"""
import argparse
import os
import shlex
import subprocess
import sys
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prodg", required=True, help="ProDG compiler folder (holds ngcld.exe)")
    ap.add_argument("--script", required=True)
    ap.add_argument("--rsp", required=True, help="ninja response file listing the objects")
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--map")
    ap.add_argument("--wrapper", default="")
    args = ap.parse_args()

    prodg = Path(args.prodg).resolve()
    out = Path(args.output)
    objs = [line.strip() for line in Path(args.rsp).read_text().splitlines() if line.strip()]
    if not objs:
        sys.exit("ngcld.py: no input objects")

    script = out.with_suffix(".ngcld.ld")
    with script.open("w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/gn2e70/ngcld.py - do not edit. */\nINPUT(\n")
        for obj in objs:
            f.write(f"    {Path(obj).as_posix()}\n")
        f.write(")\n\n")
        f.write(Path(args.script).read_text(encoding="utf-8"))

    cmd = [*shlex.split(args.wrapper), str(prodg / "ngcld.exe"),
           "--script", str(script), "-o", str(out)]
    if args.map:
        cmd.append("--print-map")
    env = dict(os.environ, SN_NGC_PATH=str(prodg))
    result = subprocess.run(cmd, env=env, capture_output=True, text=True)
    output = result.stdout + result.stderr
    if args.map:
        Path(args.map).write_text(result.stdout, encoding="utf-8")
        output = result.stderr
    # ngcld prints "Error"/"Fatal Error" lines but doesn't always exit non-zero.
    failed = result.returncode != 0 or not out.exists() or " Error " in output
    if output.strip():
        sys.stderr.write(output)
    if failed:
        out.unlink(missing_ok=True)
        sys.exit(result.returncode or 1)


if __name__ == "__main__":
    main()
